"""The gritty edge growth's shops (18 Nov, claude/grow-gritty): which business is behind which door of the new blocks.

Reads the shop lists the block builders write (map_dc/coronado/city_kit/review/grow_grt/<piece>_shops.json: label,
model, door index, kind, name, the building's world transform) and the building contracts (interiors/
room_contracts.json: doors, bays, sign boards), and writes interiors/assignment_grt.json in assignment_all.json's
format, so tools/city/rooms/room_gen_grt.gd builds the rooms and gen_shots.gd can picture them. The kinds and names
are chosen in the recipes (grt_grow_recipes.gd), by hand, for this zone: pawn, check cashing, liquor, bodega, diner,
takeout, dive bar, laundromat, barber, tattoo, thrift, botanica, tyres and parts. Boarded / dead fronts get no room.
The shared assignment_all.json and all_buildings.json are not touched (generated by other tools).
Run from the repo root: python3 -I tools/city/rooms/assign_grt.py
"""
import glob, json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
IN = os.path.join(ROOT, "map_dc/coronado/city_kit/interiors")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from assign_all import bays     # the bay split between doors (same rule as every other shop of the map)

# the gritty plates: painted boards, faded colours (room_lib.SIGN_STYLE), the rounded font for hand-painted letters
STYLE = {"pawn": ("sun", "Overpass"), "cash": ("sun", "Overpass"), "liquor": ("red", "Overpass"), "bodega": ("red", "Nunito"),
         "diner": ("cream", "Nunito"), "takeout": ("red", "Nunito"), "bar": ("black", "Nunito"), "laundry": ("teal", "Overpass"),
         "barber": ("navy", "Nunito"), "tattoo": ("black", "Overpass"), "thrift": ("cream", "Nunito"), "botanica": ("green", "Nunito"),
         "tyres": ("sun", "Overpass"), "parts": ("navy", "Overpass"), "panaderia": ("cream", "Nunito"), "phones": ("teal", "Overpass")}


def main():
    rc = json.load(open(os.path.join(IN, "room_contracts.json")))["models"]
    out = []
    for f in sorted(glob.glob(os.path.join(ROOT, "map_dc/coronado/city_kit/review/grow_grt/*_shops.json"))):
        d = json.load(open(f))
        for s in d["shops"]:
            c = rc.get(s["model"])
            if c is None:
                print("NO CONTRACT", s["model"]); continue
            bl = bays(c)
            if s["door_index"] >= len(bl):
                print("NO DOOR", d["piece"], s["label"], s["door_index"]); continue
            i, e, a, b = bl[s["door_index"]]
            extra = {}
            if s["kind"] == "tyres":      # the repair building's counter office only; the bays stay a service yard
                a, b = a, min(b, e["along"] + 4.3); extra = {"depth": 7.5}
            boards = []
            for sg in c.get("signs", []):
                if sg["facade"] == "front" and a - 0.05 <= sg["along"] <= b + 0.05: boards.append(sg)
                elif sg["facade"] == "left" and i == 0: boards.append(sg)
                elif sg["facade"] == "right" and b >= float(c["floors"][0]["box_max"][0]) - 0.05: boards.append(sg)
            rid = "grt_%s_%s_%d" % (d["piece"][2:], s["label"], i)
            st, font = STYLE.get(s["kind"], ("green", "Overpass"))
            out.append({"id": rid, "piece": d["piece"], "label": s["label"], "model": s["model"], "pos": s["pos"], "yaw": s["yaw"],
                        "door_index": i, "door_along": e["along"], "door_w": e["w"], "bay": [round(a, 3), round(b, 3)],
                        "kind": s["kind"], "name": s["name"], "style": st, "font": font, "built": "",
                        "why": "gritty growth: chosen in the recipe (grt_grow_recipes.gd)",
                        "signs": [{"facade": x["facade"], "along": x["along"], "w": x["w"]} for x in boards], **extra})
    json.dump({"_doc": __doc__.strip().split("\n")[0], "count": len(out), "rooms": out}, open(os.path.join(IN, "assignment_grt.json"), "w"), indent=1)
    print("assignment_grt.json: %d rooms" % len(out))
    for k in sorted({r["kind"] for r in out}):
        print("  %-9s %d" % (k, sum(1 for r in out if r["kind"] == k)))


if __name__ == "__main__":
    main()
